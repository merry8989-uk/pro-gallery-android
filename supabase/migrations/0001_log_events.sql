-- The diagnostics events, as the logging standard defines them.
--
-- Three decisions in this file are load-bearing, and each one is a rule the standard states:
--
-- 1. **The closed vocabularies are CHECK constraints, not conventions.** `event_name` and
--    `log_level` cannot hold anything outside the list. A column that accepts free text is a
--    column that will eventually hold a filename.
-- 2. **The table is append-only through the API.** There is an INSERT policy and nothing else —
--    no SELECT, no UPDATE, no DELETE. So a leaked publishable key can add junk and cannot read
--    one row of anybody's log. That is the whole security model, and it is the reason a
--    publishable key is safe to ship.
-- 3. **A guard rejects the things that must never be stored**, whatever the client sends. The
--    client redacts too; this is the boundary that does not depend on the client being correct.

create table if not exists public.log_events (
    id               bigint generated always as identity primary key,
    received_at      timestamptz not null default now(),

    -- The envelope, named exactly as the standard names it.
    timestamp        timestamptz not null,
    schema_version   text        not null,
    event_name       text        not null,
    log_level        text        not null,
    session_id       text        not null,
    attempt_id       text,
    user_code        text        not null,
    user_id_hash     text        not null,
    platform         text        not null default 'android',
    app_version      text        not null,
    os               text        not null,
    device_model     text        not null,
    network_type     text,
    screen_or_route  text,
    release_channel  text        not null,

    -- The event's own properties. Bounded, because an unbounded column is a dumping ground.
    details          jsonb       not null default '{}'::jsonb,

    constraint log_events_event_name_known check (event_name in (
        'session_start', 'screen_view', 'permission_state_resolved',
        'access_fix_requested', 'access_fix_result', 'media_query_result',
        'api_request', 'crash', 'anr', 'performance_marker', 'error_state_shown',
        'rage_tap', 'dead_click', 'permission_loop', 'back_button_spam',
        'scroll_depth', 'drop_off', 'time_to_first_value', 'consent_changed'
    )),
    constraint log_events_level_known   check (log_level in ('debug', 'info', 'warn', 'error')),
    constraint log_events_platform_known check (platform in ('android', 'web')),
    constraint log_events_release_known check (release_channel in ('production', 'beta')),
    constraint log_events_device_known  check (device_model in ('mobile', 'tablet', 'desktop')),
    constraint log_events_schema_known  check (schema_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$'),

    -- A code is a pseudonym with a known shape. Anything else is not one.
    constraint log_events_user_code_shape check (user_code ~ '^[A-Z]{2}-[0-9A-Z]{3}-[0-9A-Z]{3}$'),

    -- A session id is generated by the app and has a fixed prefix.
    constraint log_events_session_shape   check (session_id ~ '^sess_[0-9a-f]{16}$'),

    constraint log_events_details_bounded check (pg_column_size(details) <= 2048)
);

comment on table public.log_events is
    'Append-only diagnostics events. Written by the log-ingest function; readable only by the '
    'service role. See supabase/migrations/0001_log_events.sql for the rules this enforces.';

-- Reads are by time and by device. Both are indexed, because a table nobody can query quickly
-- is a table nobody queries.
create index if not exists log_events_timestamp_idx  on public.log_events (timestamp desc);
create index if not exists log_events_user_code_idx  on public.log_events (user_code, timestamp desc);
create index if not exists log_events_level_idx      on public.log_events (log_level) where log_level in ('warn', 'error');
create index if not exists log_events_event_name_idx on public.log_events (event_name, timestamp desc);

-- ---------------------------------------------------------------------------------------------
-- The guard: what must never be stored, rejected at the boundary.
-- ---------------------------------------------------------------------------------------------

create or replace function public.log_events_guard() returns trigger
language plpgsql
as $$
declare
    forbidden_keys text[] := array[
        'email', 'phone', 'name', 'first_name', 'last_name', 'contact',
        'path', 'file', 'filename', 'file_name', 'filepath', 'uri', 'url',
        'query', 'search', 'search_query', 'token', 'access_token', 'refresh_token',
        'password', 'secret', 'key', 'authorization', 'cookie',
        'location', 'latitude', 'longitude', 'lat', 'lon', 'address', 'gps'
    ];
    offending_key text;
    text_values   text;
begin
    -- 1. A key that names something we promised never to collect.
    select k into offending_key
    from jsonb_object_keys(new.details) as k
    where lower(k) = any (forbidden_keys)
    limit 1;

    if offending_key is not null then
        raise exception 'log_events: refusing detail key "%"', offending_key
            using errcode = 'check_violation';
    end if;

    -- 2. A value that *is* one, whatever it is called. A file path, a content URI, an email
    --    address, a long digit run (a phone number), or a URL with a query string.
    select string_agg(value, ' ') into text_values
    from jsonb_each_text(new.details) as d(k, value)
    where value ~ '(^|/)(storage|sdcard|Android|data|Download|DCIM)/'
       or value ~ '^content://'
       or value ~ '^file://'
       or value ~ '^https?://[^ ]*\?'
       or value ~ '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}'
       or value ~ '\+?[0-9][0-9 ()-]{8,}[0-9]'
       or value ~ '\.(jpg|jpeg|png|gif|webp|heic|mp4|mov|mkv|mp3|opus|pdf|docx|xlsx|zip)$';

    if text_values is not null then
        raise exception 'log_events: refusing a detail value that looks personal'
            using errcode = 'check_violation';
    end if;

    -- 3. The free-text columns get the same treatment, because they are free text.
    if new.screen_or_route is not null and (
        new.screen_or_route ~ '[/\\]' or new.screen_or_route ~ '@' or length(new.screen_or_route) > 64
    ) then
        raise exception 'log_events: screen_or_route must be a screen name, not a path'
            using errcode = 'check_violation';
    end if;

    return new;
end;
$$;

drop trigger if exists log_events_guard_trigger on public.log_events;
create trigger log_events_guard_trigger
    before insert on public.log_events
    for each row execute function public.log_events_guard();

-- ---------------------------------------------------------------------------------------------
-- Append-only through the API.
-- ---------------------------------------------------------------------------------------------

alter table public.log_events enable row level security;

-- The one and only policy. There is deliberately no SELECT, UPDATE or DELETE policy: with row
-- level security on and no policy permitting them, those operations return nothing at all.
drop policy if exists log_events_append_only on public.log_events;
create policy log_events_append_only on public.log_events
    for insert to anon, authenticated
    with check (true);

revoke all on public.log_events from anon, authenticated;
grant insert on public.log_events to anon, authenticated;
grant usage, select on sequence public.log_events_id_seq to anon, authenticated;

-- The function's own role writes freely; that is the intended path.
grant all on public.log_events to service_role;

-- ---------------------------------------------------------------------------------------------
-- Retention. The standard asks for a defined limit, so here is the limit and the way to apply it.
-- ---------------------------------------------------------------------------------------------

create or replace function public.prune_log_events(keep_days int default 30)
returns bigint
language plpgsql
security definer
as $$
declare
    removed bigint;
begin
    delete from public.log_events where received_at < now() - make_interval(days => keep_days);
    get diagnostics removed = row_count;
    return removed;
end;
$$;

comment on function public.prune_log_events(int) is
    'Deletes events older than keep_days (default 30) and returns how many went. Run it from a '
    'scheduled job; the retention limit is not enforced by itself.';
