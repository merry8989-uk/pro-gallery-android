#!/usr/bin/env python3
"""
Regenerates SettingsExport.kt from the AppSettings field list.

    python3 tools/generate_settings_export.py

The export has to name every setting, and hand-maintaining that list is how a setting
ends up silently missing from a backup. This reads AppSettings.kt and writes the
encoder and decoder, so adding a field and re-running is all it takes.
SettingsExportTest additionally checks, from the source, that nothing was skipped.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path("app/src/main/java/com/progallery/app/data/settings")
SOURCE = ROOT / "AppSettings.kt"
TARGET = ROOT / "SettingsExport.kt"
ENUMS = {"PerformanceMode", "ThemeMode", "LayoutMode", "GridSize", "SortOrder", "ExportDuplicatePolicy"}

src = SOURCE.read_text()
start = src.index("data class AppSettings(")
body = src[start:src.index(") {", start)]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
body = re.sub(r"//[^\n]*", "", body)

params = []
for line in body.split("\n"):
    line = line.strip().rstrip(",")
    m = re.match(r"val (\w+):\s*([\w.]+)\s*=", line)
    if m:
        params.append((m.group(1), m.group(2)))

enc, dec = [], []
for name, typ in params:
    if typ == "Boolean":
        enc.append(f'        "{name}" to settings.{name},')
        dec.append(f'            {name} = bool(map, "{name}", defaults.{name}),')
    elif typ == "Int":
        enc.append(f'        "{name}" to settings.{name}.toLong(),')
        dec.append(f'            {name} = int(map, "{name}", defaults.{name}),')
    elif typ == "Long":
        enc.append(f'        "{name}" to settings.{name},')
        dec.append(f'            {name} = long(map, "{name}", defaults.{name}),')
    elif typ in ENUMS:
        enc.append(f'        "{name}" to settings.{name}.name,')
        dec.append(f'            {name} = enum(map, "{name}", {typ}.entries, defaults.{name}),')
    else:
        sys.exit(f"unhandled type {typ} for {name}")

imports = "\n".join(
    f"import {pkg}"
    for pkg in ["com.progallery.app.data.model.SortOrder"]
)

TARGET.write_text(f'''package com.progallery.app.data.settings

import com.progallery.app.data.model.SortOrder

/**
 * Settings export and import.
 *
 * The file is a flat, versioned JSON object. It deliberately holds **only the user's
 * choices**: no file paths, no content URIs, no SAF grants, no tokens. A test asserts
 * that, because an export is a file the user will share or keep.
 *
 * Import is tolerant in the ways that matter — unknown keys are ignored (so a file
 * written by a newer build still loads), missing keys fall back to the current
 * defaults — and strict about the format version, so a file from a future format is
 * refused rather than silently half-applied.
 *
 * Generated by `tools/generate_settings_export.py` from the [AppSettings] field list.
 * `SettingsExportTest` reads the same source and fails if a field is missing here, so
 * a new setting cannot quietly drop out of a backup.
 */
object SettingsExport {{

    const val FORMAT_VERSION = 1
    private const val KEY_FORMAT = "formatVersion"

    /** The names the export writes, in order, excluding the format marker. */
    val FIELD_NAMES: List<String> = listOf(
{chr(10).join(f'        "{name}",' for name, _ in params)}
    )

    /** The user's choices as versioned JSON. */
    fun encode(settings: AppSettings): String = FlatJson.encode(
        linkedMapOf<String, Any?>(
            KEY_FORMAT to FORMAT_VERSION.toLong(),
{chr(10).join(enc)}
        ),
    )

    /**
     * Reads an export back.
     *
     * Fails with a readable message on malformed input or an unsupported format
     * version, and never returns settings that break the app's own invariants —
     * the result is passed through [AppSettings.sanitized].
     */
    fun decode(json: String): Result<AppSettings> {{
        val map = try {{
            FlatJson.decode(json)
        }} catch (t: IllegalArgumentException) {{
            return Result.failure(IllegalArgumentException("This is not a valid settings file.", t))
        }}

        val version = (map[KEY_FORMAT] as? Long)?.toInt()
            ?: return Result.failure(
                IllegalArgumentException(
                    "This file has no format version, so it was not written by ProGallery.",
                ),
            )

        if (version > FORMAT_VERSION) {{
            return Result.failure(
                IllegalArgumentException(
                    "This settings file is from a newer version of the app " +
                        "(format $version, this build reads $FORMAT_VERSION).",
                ),
            )
        }}

        val defaults = AppSettings.Defaults
        val imported = AppSettings(
{chr(10).join(dec)}
        )
        return Result.success(imported.sanitized())
    }}

    private fun bool(map: Map<String, Any?>, key: String, fallback: Boolean): Boolean =
        map[key] as? Boolean ?: fallback

    private fun int(map: Map<String, Any?>, key: String, fallback: Int): Int =
        (map[key] as? Long)?.coerceIn(Int.MIN_VALUE.toLong(), Int.MAX_VALUE.toLong())?.toInt()
            ?: fallback

    private fun long(map: Map<String, Any?>, key: String, fallback: Long): Long =
        map[key] as? Long ?: fallback

    private fun <T : Enum<T>> enum(
        map: Map<String, Any?>,
        key: String,
        values: List<T>,
        fallback: T,
    ): T {{
        val raw = map[key] as? String ?: return fallback
        return values.firstOrNull {{ it.name == raw }} ?: fallback
    }}
}}
''')
print(f"SettingsExport.kt regenerated with {len(params)} fields")
